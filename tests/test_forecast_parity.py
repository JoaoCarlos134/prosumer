"""The library's LightGBM against the benchmark's saved forecasts: the forecasts must be the SAME numbers.

Step E3 of the plan in its strong form: not the metrics recomputed from saved forecasts (that is
`test_benchmark_regression.py`), but the forecasts themselves regenerated by `prosumer.forecast` with the
benchmark's protocol (`comum.tarefa`, which is built on `prosumer.protocol`). Checked on 2026-10-11: the nine
case/regime combinations agree to <= 3.5e-18.

By default two combinations run (~30 s): the houses' PV with history only and the plants in regime C, with the
weather forecast and the clear-sky persistence. `PROSUMER_FULL=1` runs the nine (~3 min).
"""

from __future__ import annotations

import importlib
import os
import sys
from pathlib import Path
from types import ModuleType

import numpy as np
import pandas as pd
import pytest

pytest.importorskip("lightgbm")
pytest.importorskip("sklearn")

from prosumer.forecast import LightGBM, rolling_forecast

BENCH = Path(__file__).resolve().parents[1] / "experimentos" / "testes_previsao"
SCRIPTS = BENCH / "scripts"
pytestmark = pytest.mark.skipif(
    not (BENCH / "dados" / "usinas_horario.parquet").exists(), reason="benchmark data missing"
)
QUICK = {("casas_prod", "A"), ("usinas", "C")}
ALL = [
    *[("usinas", r) for r in ("A", "B", "C", "B-curto", "C-gfs")],
    ("casas_prod", "A"),
    ("casas_prod", "B"),
    ("casas_cons", "A"),
    ("casas_cons", "B"),
]


def _comum() -> ModuleType:
    sys.path.insert(0, str(SCRIPTS))
    return importlib.import_module("comum")


@pytest.mark.parametrize(("case", "regime"), ALL)
def test_lightgbm_regenerates_the_benchmark_forecasts(case: str, regime: str) -> None:
    if (case, regime) not in QUICK and os.environ.get("PROSUMER_FULL") != "1":
        pytest.skip("set PROSUMER_FULL=1 for the nine combinations")
    comum = _comum()
    weather = regime != "A"
    task = comum.tarefa(comum.carrega(case, regime), case, contexto=168, exog=weather)
    model = LightGBM(comum.EXOG, clear_sky="poa_ceu_claro") if weather else LightGBM()
    ours = rolling_forecast(model, task)
    saved = pd.read_parquet(comum.PREV / f"LightGBM__{case}__{regime}.parquet")
    saved["ds"] = saved["ds"].dt.tz_localize(comum.FUSO[case])
    m = ours.merge(
        saved[["unique_id", "ds", "yhat"]], on=["unique_id", "ds"], how="outer", suffixes=("", "_saved")
    )
    assert len(m) == len(ours) == len(saved), "the same series-hours must be forecast"
    np.testing.assert_allclose(m["yhat"], m["yhat_saved"], rtol=0, atol=1e-12)


@pytest.mark.parametrize(("case", "regime"), [("casas_prod", "A"), ("usinas", "C")])
def test_lightgbm_quantile_regenerates_the_band_pilot(case: str, regime: str) -> None:
    """The 9 quantiles of pilot F2(c) (`piloto_quantis.py gera LightGBM`), regenerated by the library
    (checked 2026-10-11: identical, max |dif| 0.0). ~40-50 s each: only with PROSUMER_FULL=1."""
    if os.environ.get("PROSUMER_FULL") != "1":
        pytest.skip("set PROSUMER_FULL=1")
    from prosumer.forecast import LightGBMQuantile, rolling_quantiles

    comum = _comum()
    weather = regime != "A"
    task = comum.tarefa(comum.carrega(case, regime), case, contexto=168, exog=weather)
    model = LightGBMQuantile(comum.EXOG, clear_sky="poa_ceu_claro") if weather else LightGBMQuantile()
    ours = rolling_quantiles(model, task).drop(columns="yhat")
    ours = ours.melt(id_vars=["unique_id", "ds"], var_name="q", value_name="valor")
    ours["q"] = ours["q"].str[1:].astype(float)
    saved = pd.read_parquet(BENCH / "resultados" / "pilotos" / f"LightGBM-quantis__{case}__{regime}.parquet")
    saved["ds"] = saved["ds"].dt.tz_localize(comum.FUSO[case])
    m = ours.merge(saved, on=["unique_id", "ds", "q"], how="outer", suffixes=("", "_saved"))
    assert len(m) == len(ours) == len(saved)
    np.testing.assert_allclose(m["valor"], m["valor_saved"], rtol=0, atol=1e-12)
